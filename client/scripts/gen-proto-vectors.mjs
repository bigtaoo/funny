// Regenerates client/test/_proto_vectors.json — the authoritative server-side byte vectors
// proto-wire-compat.test.ts cross-checks the client ts-proto codec against.
//
// Loads ../../server/contracts/transport.proto independently via protobufjs (same mechanism
// server/gameserver/test/transport.test.ts uses to cross-check the server's own hand-written
// codec), builds one sample message per ClientMsg/ServerMsg oneof case, encodes each with
// protobufjs, and writes the hex bytes out. This is the "authoritative server bytes" half of the
// interop test — the client half (ts-proto, generated by `npm run proto:gen`) is exercised by
// proto-wire-compat.test.ts itself, not by this script.
//
// Run: node scripts/gen-proto-vectors.mjs (from client/), then re-run `npm test
// proto-wire-compat` to confirm interop. Re-run whenever transport.proto gains/changes a oneof
// case — this is the previously-undocumented "regenerate the vectors" step
// proto-wire-compat.test.ts's header comment refers to.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..'); // client/
const PROTO = join(root, '..', 'server', 'contracts', 'transport.proto');
const OUT = join(root, 'test', '_proto_vectors.json');

// protobufjs lives in server/'s workspace node_modules (gameserver/gateway depend on it), not
// client's — resolve it from there rather than adding a client-side dependency just for this
// one-off regen script.
const requireFromServer = createRequire(join(root, '..', 'server', 'package.json'));
const protobuf = requireFromServer('protobufjs');

const proto = protobuf.parse(readFileSync(PROTO, 'utf8'), { keepCase: true }).root;
const Envelope = proto.lookupType('nw.transport.Envelope');

const toHex = (bytes) => Buffer.from(bytes).toString('hex');
const encodeClient = (body) => toHex(Envelope.encode(Envelope.fromObject({ client: body })).finish());
const encodeServer = (body) => toHex(Envelope.encode(Envelope.fromObject({ server: body })).finish());

// One representative sample per ClientMsg oneof case (field 1..13 in transport.proto).
const client = {
  room_create: encodeClient({ room_create: { mode: 0 } }),
  room_join: encodeClient({ room_join: { code: 'ABC234' } }),
  room_ready: encodeClient({ room_ready: { ready: true } }),
  room_leave: encodeClient({ room_leave: {} }),
  room_start: encodeClient({ room_start: {} }),
  cmd_submit: encodeClient({ cmd_submit: { commands: Uint8Array.from([1, 2, 3, 255]) } }),
  match_result: encodeClient({ match_result: { state_hash: 'deadbeef' } }),
  conn_resume: encodeClient({ conn_resume: { room_id: 'room-1', last_frame: 42 } }),
  ping: encodeClient({ ping: {} }),
  client_caps: encodeClient({ client_caps: { can_judge: true } }),
  judge_verdict: encodeClient({
    judge_verdict: {
      request_id: 'req-1', state_hash: 'cafebabe', winner_side: 1, ok: true,
      stars: 3, stats_json: '{"kill.archer":2}',
    },
  }),
  duel_invite: encodeClient({ duel_invite: { to_public_id: '123456789', deck: ['card_a', 'card_b'] } }),
  duel_respond: encodeClient({ duel_respond: { invite_id: 'inv-1', accept: true, deck: ['card_a'] } }),
};

